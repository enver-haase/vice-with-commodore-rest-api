#!/bin/sh
# Rebuilds vice/src/restapi_sidcrt.h, the SID player cartridge runners:sidplay
# starts, from the sources in restapi-sidcrt/.
#
# The sources are Wilfred Bos' "Ultimate SID Player", taken unchanged from the
# 1541-Ultimate firmware at tag 1.1.0 (Commodore's release, commit 7b628eb1).
# They are assembled the way that firmware's Makefile does it, with the 64tass
# it ships (tools/64tass, V1.53.1515): newer releases reject the source. That
# binary is x86-64 Linux, so it runs in Docker here.
#
# Needs docker, curl and python3. The result must match the checksum below; a
# different one means the sources or the assembler changed.
set -e
here=$(cd "$(dirname "$0")" && pwd)
expected=85540bc9ea07dbc84b610af60d8bae87324945f7747c59e299063ee240403a97
tool=https://raw.githubusercontent.com/enver-haase/1541ultimate/1.1.0/tools/64tass/64tass

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cp -R "$here/restapi-sidcrt/." "$work/"
curl -fsSL -o "$work/64tass" "$tool"
chmod +x "$work/64tass"

docker run --rm --platform linux/amd64 -v "$work:/w" -w /w ubuntu:24.04 sh -c '
  set -e
  mkdir -p target
  ./64tass --nostart -o target/player.bin player/player.asm
  ./64tass --nostart -D INCLUDE_RUNSTOP=0 -o target/advancedplayer.bin player/advanced/advancedplayer.asm
  ./64tass -o target/sidcrt.bin -b sidcrt.asm
'

python3 - "$work/target/sidcrt.bin" "$here/vice/src/restapi_sidcrt.h" "$expected" <<'EOF'
import hashlib, sys
data = open(sys.argv[1], 'rb').read()
digest = hashlib.sha256(data).hexdigest()
if digest != sys.argv[3]:
    sys.exit('sidcrt.bin has sha256 %s, expected %s' % (digest, sys.argv[3]))
lines = []
for i in range(0, len(data), 16):
    lines.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
open(sys.argv[2], 'w').write('''/** \\file   restapi_sidcrt.h
 *  \\brief  The SID player cartridge of the 1541-Ultimate firmware 1.1.0
 *
 *  Generated by restapi-sidcrt.sh from restapi-sidcrt/, do not edit.
 *
 *  "Ultimate SID Player V2.0d", Copyright (c) 2009-2023 Wilfred Bos / Gideon
 *  Zweijtzer, part of the 1541-Ultimate firmware and licensed with it under
 *  the GNU General Public License version 3. Assembled from the sources at the
 *  firmware's tag 1.1.0 (commit 7b628eb1) with its own 64tass V1.53.1515.
 *
 *  %d bytes, sha256 %s
 */

#ifndef VICE_RESTAPI_SIDCRT_H
#define VICE_RESTAPI_SIDCRT_H

static const unsigned char restapi_sidcrt[%d] = {
%s
};

#endif
''' % (len(data), digest, len(data), '\n'.join(lines)))
print('wrote %s, %d bytes, sha256 %s' % (sys.argv[2], len(data), digest))
EOF
